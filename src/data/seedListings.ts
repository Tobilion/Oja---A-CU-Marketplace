// Helper to create clean vector SVG data URIs for robust, hermetic offline display
function createSvgDataUri(bg: string, fg: string, title: string, category: string): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="450" viewBox="0 0 600 450">
    <rect width="600" height="450" fill="${bg}"/>
    <circle cx="300" cy="180" r="70" fill="${fg}" opacity="0.15"/>
    <text x="300" y="190" font-family="system-ui, sans-serif" font-size="28" font-weight="bold" fill="${fg}" text-anchor="middle">${category}</text>
    <rect x="50" y="320" width="500" height="80" rx="8" fill="#ffffff" opacity="0.95"/>
    <text x="300" y="365" font-family="system-ui, sans-serif" font-size="19" font-weight="600" fill="#1e293b" text-anchor="middle">${title.length > 38 ? title.slice(0, 36) + '...' : title}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

